"""
Execution result for workflow nodes.

NodeResult wraps the business output (NodeOutput) together with
execution metadata such as success, timing, warnings, and errors.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime, UTC
from typing import Any

from app.nodes.base.node_output import NodeOutput


@dataclass(slots=True)
class NodeResult:
    """
    Result returned after executing a workflow node.

    Attributes:
        success:
            Indicates whether execution completed successfully.

        output:
            Business output generated by the node.

        error:
            Exception or error message if execution failed.

        warnings:
            Non-fatal warnings generated during execution.

        metrics:
            Execution metrics such as token usage, latency, etc.

        started_at:
            Execution start time.

        completed_at:
            Execution completion time.

        duration_ms:
            Total execution time in milliseconds.
    """

    success: bool

    output: NodeOutput | None = None

    error: Exception | str | None = None

    warnings: list[str] = field(default_factory=list)

    metrics: dict[str, Any] = field(default_factory=dict)

    started_at: datetime = field(default_factory=lambda: datetime.now(UTC))

    completed_at: datetime | None = None

    duration_ms: float | None = None

    # ------------------------------------------------------------------
    # Factory Methods
    # ------------------------------------------------------------------

    @classmethod
    def success_result(
        cls,
        output: NodeOutput,
        *,
        metrics: dict[str, Any] | None = None,
        warnings: list[str] | None = None,
        duration_ms: float | None = None,
    ) -> "NodeResult":
        """Create a successful execution result."""
        return cls(
            success=True,
            output=output,
            metrics=metrics or {},
            warnings=warnings or [],
            completed_at=datetime.now(UTC),
            duration_ms=duration_ms,
        )

    @classmethod
    def failure_result(
        cls,
        error: Exception | str,
        *,
        metrics: dict[str, Any] | None = None,
        duration_ms: float | None = None,
    ) -> "NodeResult":
        """Create a failed execution result."""
        return cls(
            success=False,
            error=error,
            metrics=metrics or {},
            completed_at=datetime.now(UTC),
            duration_ms=duration_ms,
        )

    # ------------------------------------------------------------------
    # Warnings
    # ------------------------------------------------------------------

    def add_warning(self, message: str) -> None:
        """Add a non-fatal warning."""
        self.warnings.append(message)

    # ------------------------------------------------------------------
    # Metrics
    # ------------------------------------------------------------------

    def add_metric(self, name: str, value: Any) -> None:
        """Record an execution metric."""
        self.metrics[name] = value

    def get_metric(self, name: str, default: Any = None) -> Any:
        """Retrieve an execution metric."""
        return self.metrics.get(name, default)

    # ------------------------------------------------------------------
    # Utilities
    # ------------------------------------------------------------------

    @property
    def failed(self) -> bool:
        """Return True if execution failed."""
        return not self.success

    def to_dict(self) -> dict[str, Any]:
        """Serialize the result."""
        return {
            "success": self.success,
            "output": self.output.to_dict() if self.output else None,
            "error": str(self.error) if self.error else None,
            "warnings": self.warnings,
            "metrics": self.metrics,
            "started_at": self.started_at.isoformat(),
            "completed_at": (
                self.completed_at.isoformat()
                if self.completed_at
                else None
            ),
            "duration_ms": self.duration_ms,
        }